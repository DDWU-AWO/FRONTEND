function fallbackResult(step) {
  if (step.resultType === 'outline') {
    return {
      content: `# ${step.name}\n\n${step.description}\n\n1. **도입**\\\n   다룰 내용을 소개해요.\n2. **본론**\\\n   핵심 내용을 차례로 설명해요.\n3. **마무리**\\\n   정리하고 다음 할 일을 안내해요.`,
    };
  }
  if (step.resultType === 'review') {
    return {
      content: `# ${step.name}\n\n고친 내용을 반영한 최종 글이에요.`,
      review: {
        description: '맞춤법과 띄어쓰기를 고쳤어요. 원래 문장과 고친 문장, 고친 이유를 함께 확인하세요.',
        corrections: CORRECTIONS.slice(0, 2),
      },
    };
  }
  return {
    content: `# ${step.name} 결과\n\n${step.description}\n\n## 1. 핵심 내용\n\n${step.agent}가 정리한 핵심 내용이에요.\n\n## 2. 참고할 점\n\n다음 단계에서 확인하면 좋은 내용을 모았어요.`,
  };
}

export function getMockResult(step) {
  const example = BLOG_RESULTS[step.name] ?? fallbackResult(step);
  const points = example.handoff ?? [`${step.name} 결과의 핵심 내용`, step.volume, '다음 단계에 필요한 조건'];
  return {
    content: example.content,
    review: example.review,
    handoff: {
      summary: HANDOFF_SUMMARY,
      points,
      full: `${step.agent}가 정리한 내용 중 다음 단계에 꼭 필요한 것만 골라 전달했어요.\n\n${points
        .map((p) => `- ${p}`)
        .join('\n')}`,
    },
  };
}
